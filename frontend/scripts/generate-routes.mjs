// Generate the flat file-route tree used by this local SPA. Route source files
// retain TanStack createFileRoute and remain directly addressable.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export async function generateRoutes() {
  const files = (await readdir(path.join(root, "src/routes")))
    .filter((f) => f.endsWith(".tsx") && !f.startsWith("__"))
    .sort();
  const routes = [];
  for (const file of files) {
    const source = await readFile(path.join(root, "src/routes", file), "utf8");
    const match = source.match(/createFileRoute\(['"]([^'"]+)['"]\)/);
    if (!match) throw new Error(`Missing file route declaration in ${file}`);
    routes.push({ id: `R${routes.length}`, file: file.slice(0, -4), url: match[1] });
  }
  if (new Set(routes.map((r) => r.url)).size !== routes.length)
    throw new Error("Duplicate file routes");
  const text =
    `/* eslint-disable */\n// @ts-nocheck\n// Automatically generated by scripts/generate-routes.mjs. Do not edit.\nimport { Route as rootRouteImport } from './routes/__root';\n` +
    routes.map((r) => `import { Route as ${r.id}Import } from './routes/${r.file}';\n`).join("") +
    routes
      .map(
        (r) =>
          `const ${r.id} = ${r.id}Import.update({id:'${r.url}',path:'${r.url}',getParentRoute:()=>rootRouteImport} as any);\n`,
      )
      .join("") +
    `declare module '@tanstack/react-router' { interface FileRoutesByPath {\n` +
    routes
      .map(
        (r) =>
          `'${r.url}': {id:'${r.url}';path:'${r.url}';fullPath:'${r.url}';preLoaderRoute:typeof ${r.id}Import;parentRoute:typeof rootRouteImport};\n`,
      )
      .join("") +
    `}}\nexport const routeTree = rootRouteImport.addChildren([${routes.map((r) => r.id).join(",")}]);\n`;
  const target = path.join(root, "src/routeTree.gen.ts");
  if ((await readFile(target, "utf8").catch(() => "")) !== text) await writeFile(target, text);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await generateRoutes();
